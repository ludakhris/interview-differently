-- SQL Fundamentals
-- Sandbox + assessment dataset for the Code Differently Data Analysis cohort: customers, orders,
-- order_items, products, plus a deliberately dirty customers_messy table.
-- Deterministic: no RANDOM()/NOW(). Order dates are relative to CURRENT_DATE so
-- "last 30 / 90 days" questions keep working. Regenerate, don't hand-edit rows.

CREATE TABLE customers (
  customer_id INT PRIMARY KEY,
  first_name  TEXT NOT NULL,
  last_name   TEXT NOT NULL,
  email       TEXT,
  city        TEXT,
  state       TEXT,
  country     TEXT,
  signup_date DATE NOT NULL
);
CREATE TABLE products (
  product_id   INT PRIMARY KEY,
  product_name TEXT NOT NULL,
  category     TEXT NOT NULL,
  unit_cost    NUMERIC(10,2) NOT NULL,
  stock_qty    INT NOT NULL,
  is_active    BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE orders (
  order_id     INT PRIMARY KEY,
  customer_id  INT NOT NULL REFERENCES customers(customer_id),
  order_date   DATE NOT NULL,
  status       TEXT NOT NULL,
  shipped_date DATE
);
CREATE TABLE order_items (
  order_item_id INT PRIMARY KEY,
  order_id      INT NOT NULL REFERENCES orders(order_id),
  product_id    INT NOT NULL REFERENCES products(product_id),
  quantity      INT NOT NULL,
  unit_price    NUMERIC(10,2) NOT NULL
);
-- Same shape as customers, deliberately dirty: casing/whitespace on state, NULL emails, signup_date as TEXT.
CREATE TABLE customers_messy (
  customer_id INT PRIMARY KEY,
  first_name  TEXT,
  last_name   TEXT,
  email       TEXT,
  city        TEXT,
  state       TEXT,
  country     TEXT,
  signup_date TEXT
);

